def invoice_details(
    payload,
    user_id,
):
    parts = payload.split(":")

    if len(parts) != 5:
        return None

    kind = parts[0]
    topic = parts[1]
    period = parts[2]
    payload_user_id = parts[3]
    payment_nonce = parts[4]

    if not valid_reading_params(
        kind,
        topic,
        period,
    ):
        return None

    if payload_user_id != str(user_id):
        return None

    if len(payment_nonce) != 32:
        return None

    return (
        kind,
        topic,
        period,
    )


