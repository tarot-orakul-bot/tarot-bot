def touch_user(user_id):
    with db() as conn:
        conn.execute("""
            INSERT INTO users (
                user_id,
                created_at,
                last_seen,
                reminder_sent_at
            )
            VALUES (%s, now(), now(), NULL)

            ON CONFLICT (user_id)
            DO UPDATE SET
                last_seen = now(),
                reminder_sent_at = NULL
        """, (user_id,))


def claim_free(user_id, field):
    with db() as conn:
        if field == "three_used":
            row = conn.execute("""
                INSERT INTO users (
                    user_id,
                    three_used,
                    created_at,
                    last_seen,
                    reminder_sent_at
                )
                VALUES (%s, TRUE, now(), now(), NULL)

                ON CONFLICT (user_id)
                DO UPDATE SET
                    three_used = TRUE,
                    last_seen = now(),
                    reminder_sent_at = NULL
                WHERE users.three_used = FALSE

                RETURNING user_id
            """, (user_id,)).fetchone()

        else:
            if field not in (
                "daily_card",
                "daily_question",
            ):
                raise ValueError(
                    "Неизвестная бесплатная функция"
                )

            today = datetime.now(TZ).date()

            row = conn.execute(f"""
                INSERT INTO users (
                    user_id,
                    {field},
                    created_at,
                    last_seen,
                    reminder_sent_at
                )
                VALUES (%s, %s, now(), now(), NULL)

                ON CONFLICT (user_id)
                DO UPDATE SET
                    {field} = EXCLUDED.{field},
                    last_seen = now(),
                    reminder_sent_at = NULL
                WHERE users.{field}
                    IS DISTINCT FROM EXCLUDED.{field}

                RETURNING user_id
            """, (
                user_id,
                today,
            )).fetchone()

        return row is not None


