def activate_promo(user_id, code):
    normalized_code = code.strip().upper()

    if normalized_code != PROMO_CODE:
        return "invalid", 0

    with db() as conn:
        row = conn.execute("""
            INSERT INTO users (
                user_id,
                promo_code,
                promo_credits,
                created_at,
                last_seen
            )
            VALUES (
                %s,
                %s,
                %s,
                now(),
                now()
            )

            ON CONFLICT (user_id)
            DO UPDATE SET
                promo_code = EXCLUDED.promo_code,
                promo_credits = EXCLUDED.promo_credits,
                last_seen = now(),
                reminder_sent_at = NULL
            WHERE users.promo_code IS NULL

            RETURNING promo_credits
        """, (
            user_id,
            PROMO_CODE,
            PROMO_CREDITS,
        )).fetchone()

        if row:
            return "activated", row[0]

        current = conn.execute("""
            UPDATE users
            SET
                last_seen = now(),
                reminder_sent_at = NULL
            WHERE user_id = %s
            RETURNING promo_credits
        """, (user_id,)).fetchone()

        return (
            "already",
            current[0] if current else 0,
        )


def claim_promo_credit(user_id):
    with db() as conn:
        row = conn.execute("""
            UPDATE users
            SET
                promo_credits = promo_credits - 1,
                last_seen = now(),
                reminder_sent_at = NULL
            WHERE user_id = %s
              AND promo_credits > 0
            RETURNING promo_credits
        """, (user_id,)).fetchone()

        if not row:
            return None

        return row[0]


