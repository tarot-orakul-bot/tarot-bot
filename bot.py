@bot.message_handler(
    content_types=[
        "successful_payment"
    ]
)
def payment_success(message):
    touch_user(
        message.from_user.id
    )

    payment = (
        message.successful_payment
    )

    details = invoice_details(
        payment.invoice_payload,
        message.from_user.id,
    )

    if (
        not details
        or payment.currency != "XTR"
        or payment.total_amount != PRICE
    ):
        bot.send_message(
            message.chat.id,
            "⚠️ Платёж получен, "
            "но результат требует проверки.\n\n"
            "Напиши /paysupport.",
        )
        return

    kind, topic, period = details

    charge_id = (
        payment.telegram_payment_charge_id
    )

    with db() as conn:
        existing = conn.execute(
            """
            SELECT
                user_id,
                result,
                delivered
            FROM payments
            WHERE charge_id = %s
            """,
            (charge_id,),
        ).fetchone()

    if existing:
        if (
            existing[0]
            != message.from_user.id
        ):
            return

        if existing[2]:
            return

        result = existing[1]

    else:
        result = spread(
            kind,
            topic,
            period,
        )

        with db() as conn:
            conn.execute("""
                INSERT INTO payments (
                    charge_id,
                    user_id,
                    kind,
                    result,
                    delivered,
                    topic,
                    period,
                    amount
                )
                VALUES (
                    %s,
                    %s,
                    %s,
                    %s,
                    FALSE,
                    %s,
                    %s,
                    %s
                )

                ON CONFLICT (charge_id)
                DO NOTHING
            """, (
                charge_id,
                message.from_user.id,
                kind,
                result,
                topic,
                period,
                payment.total_amount,
            ))

            stored = conn.execute(
                """
                SELECT
                    user_id,
                    result,
                    delivered
                FROM payments
                WHERE charge_id = %s
                """,
                (charge_id,),
            ).fetchone()

        if not stored:
            bot.send_message(
                message.chat.id,
                "⚠️ Платёж получен, "
                "но возникла ошибка выдачи.\n\n"
                "Напиши /paysupport.",
            )
            return

        if (
            stored[0]
            != message.from_user.id
        ):
            return

        if stored[2]:
            return

        result = stored[1]

    try:
        bot.send_message(
            message.chat.id,
            "✅ Оплата успешно получена!\n\n"
            "🔮 Твой расклад готов.",
        )

        bot.send_message(
            message.chat.id,
            result,
        )

    except Exception:
        return

    with db() as conn:
        conn.execute(
            """
            UPDATE payments
            SET delivered = TRUE
            WHERE charge_id = %s
            """,
            (charge_id,),
        )

    clear_pending_reading(
        message.from_user.id
    )


