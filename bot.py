@bot.callback_query_handler(
    func=lambda c:
    c.data
    and c.data.startswith("period:")
)
def period_callback(call):
    touch_user(call.from_user.id)

    period = call.data.removeprefix(
        "period:"
    )

    if period not in PERIODS:
        answer(
            call,
            "Период не найден",
        )
        return

    kind, topic, _ = (
        get_pending_reading(
            call.from_user.id
        )
    )

    if not valid_reading_params(
        kind,
        topic,
        period,
    ):
        answer(
            call,
            "Этот выбор уже неактуален",
        )

        bot.send_message(
            call.message.chat.id,
            "Начни новый расклад через кнопку "
            "«✨ Сделать расклад».",
            reply_markup=main_keyboard(),
        )
        return

    set_pending_reading(
        call.from_user.id,
        kind=kind,
        topic=topic,
        period=period,
    )

    answer(call)

    bot.send_message(
        call.message.chat.id,
        "✨ Параметры расклада выбраны:\n\n"
        f"🎯 {topic_name(kind, topic)}\n"
        f"⏳ {period_name(period)}\n\n"
        "Перемешиваю колоду… 🔮",
    )

    if kind == "three":
        if claim_free(
            call.from_user.id,
            "three_used",
        ):
            result = spread(
                kind,
                topic,
                period,
            )

            clear_pending_reading(
                call.from_user.id
            )

            bot.send_message(
                call.message.chat.id,
                "🎁 Это твой первый расклад "
                "«3 карты», поэтому он бесплатный.",
            )

            bot.send_message(
                call.message.chat.id,
                result,
            )

            return

    remaining = claim_promo_credit(
        call.from_user.id
    )

    if remaining is not None:
        result = spread(
            kind,
            topic,
            period,
        )

        clear_pending_reading(
            call.from_user.id
        )

        bot.send_message(
            call.message.chat.id,
            "🎁 Использован бесплатный расклад "
            "по промокоду.\n\n"
            f"Осталось бесплатных раскладов: "
            f"{remaining}.",
        )

        bot.send_message(
            call.message.chat.id,
            result,
        )

        return

    offer_payment(
        call.message.chat.id,
        call.from_user.id,
        kind,
        topic,
        period,
    )


