def db():
    return psycopg.connect(
        DATABASE_URL,
        connect_timeout=5,
    )


def init_db():
    with db() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                user_id BIGINT PRIMARY KEY,
                daily_card DATE,
                daily_question DATE,
                three_used BOOLEAN NOT NULL DEFAULT FALSE,
                terms_accepted BOOLEAN NOT NULL DEFAULT FALSE,
                support_pending BOOLEAN NOT NULL DEFAULT FALSE
            )
        """)

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS promo_code TEXT
        """)

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS promo_credits
            INTEGER NOT NULL DEFAULT 0
        """)

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ
        """)

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS last_seen TIMESTAMPTZ
        """)

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS pending_kind TEXT
        """)

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS pending_topic TEXT
        """)

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS pending_period TEXT
        """)

        # Настройки мягких напоминаний
        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS reminders_enabled
            BOOLEAN NOT NULL DEFAULT TRUE
        """)

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS reminder_sent_at TIMESTAMPTZ
        """)

        conn.execute("""
            UPDATE users
            SET created_at = COALESCE(created_at, now())
            WHERE created_at IS NULL
        """)

        conn.execute("""
            UPDATE users
            SET last_seen = COALESCE(last_seen, created_at, now())
            WHERE last_seen IS NULL
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS payments (
                charge_id TEXT PRIMARY KEY,
                user_id BIGINT NOT NULL,
                kind TEXT NOT NULL,
                result TEXT NOT NULL,
                delivered BOOLEAN NOT NULL DEFAULT FALSE
            )
        """)

        conn.execute("""
            ALTER TABLE payments
            ADD COLUMN IF NOT EXISTS topic TEXT
        """)

        conn.execute("""
            ALTER TABLE payments
            ADD COLUMN IF NOT EXISTS period TEXT
        """)

        # Фактическая сумма платежа.
        # Новые платежи сохраняют реальное total_amount Telegram.
